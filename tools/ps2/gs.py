def dir32(x, y, bw):
    """direccion en palabras de 32 bits del pixel (x, y) en PSMCT32, ancho de bufer bw (unidades de 64)"""
    pg = (y >> 5) * bw + (x >> 6)
    return pg * 2048 + BT32[(y >> 3) & 3, (x >> 3) & 7] * 64 + CT32[y & 7, x & 7]

def dir16(x, y, bw):
    """direccion en medias palabras de PSMCT16"""
    pg = (y >> 6) * bw + (x >> 6)
    return pg * 4096 + BT16[(y >> 3) & 7, (x >> 4) & 3] * 128 + CT16[y & 7, x & 15]

def dir8(x, y, bw):
    """direccion en bytes de PSMT8 (bw par en unidades de 64)"""
    pg = (y >> 6) * (bw >> 1) + (x >> 7)
    return pg * 8192 + BT8[(y >> 4) & 3, (x >> 4) & 7] * 256 + CT8[y & 15, x & 15]

def dir4(x, y, bw):
    """direccion en nibbles de PSMT4"""
    pg = (y >> 7) * (bw >> 1) + (x >> 7)
    return pg * 16384 + BT4[(y >> 4) & 7, (x >> 5) & 3] * 512 + CT4[y & 15, x & 31]

def desordena(datos, psm, w, h):
    """datos tal como se suben al GS: PSMT8 como rectangulo PSMCT32 de w/2 x h/2, PSMT4 como PSMCT16 de w/2 x h/2.
    Devuelve la imagen w x h de indices."""
    wu, hu = w // 2, h // 2
    bw = max(2, (w + 63) // 64); bw += bw & 1
    mem = np.zeros(bw * 64 * (h + 128) * 4, np.uint8)
    y, x = np.mgrid[0:hu, 0:wu]
    if psm == 0x13:
        mem.view(np.uint32)[dir32(x, y, bw)] = np.frombuffer(datos[:wu * hu * 4], '<u4').reshape(hu, wu)
        y, x = np.mgrid[0:h, 0:w]
        return mem[dir8(x, y, bw)]
    mem.view(np.uint16)[dir16(x, y, bw)] = np.frombuffer(datos[:wu * hu * 2], '<u2').reshape(hu, wu)
    y, x = np.mgrid[0:h, 0:w]
    a = dir4(x, y, bw)
    return (mem[a >> 1] >> ((a & 1) * 4)) & 15
